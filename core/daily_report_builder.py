def _get_dominant_hanja(five_elements: dict[str, int]) -> str:
    """오행 분포에서 가장 강한 원소를 한자 키로 반환."""
    if not five_elements:
        return "土"
    dominant_en = max(five_elements, key=five_elements.get)
    return _EN_TO_HANJA.get(dominant_en, "土")


def build_daily_report(saju_result) -> dict:
    """
    SajuResult 객체를 받아, 강한 오행을 추출하고
    비즈니스 전략 코치 페르소나에 맞춘 데일리 리포트 JSON 반환.
    """
    elems = saju_result.five_elements if saju_result and hasattr(saju_result, "five_elements") else {}
    dominant_hanja = _get_dominant_hanja(elems)

    data = _ELEMENT_DATA.get(dominant_hanja, _ELEMENT_DATA["土"])
    summary = _ONE_LINE_SUMMARY.get(dominant_hanja, _ONE_LINE_SUMMARY["土"])

    return {
        "one_line_summary": summary,
        "detailed_fortune": data["detailed_fortune"],
        "coaching": data["coaching"],
    }
